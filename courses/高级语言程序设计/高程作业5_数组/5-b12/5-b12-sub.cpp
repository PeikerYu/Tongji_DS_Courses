/***************************************************************************
  函数名称：
  功    能：比较字符串 s1和 s2的大小，英文字母不分大小写。
    例：tj_strcasecmp("abc","ABZ"); tj_strcasecmp("ABC", "abz"); 均返回-23
    例：tj_strcasecmp("abZ","AB["); tj strcasecmp(abz", "AB["); 均返回31
  输入参数：
  返 回 值：相等为0，不等则为第1个不相等字符的ASCII差值
    若不相等处字符是不同的大小写字母，则统一转换为小写后比较
    若不相等处是大写字母和其它字符，则返回对应小写字母和其它字符的差值
  说    明：
***************************************************************************/
int tj_strcasecmp(const char s1[], const char s2[])
{
    /* 注意：函数内不允许定义任何形式的数组（包括静态数组） */
    int i = 0;
    int c1, c2; // 用于存储转换后的字符
    for (i = 0; s1[i] != '\0' && s2[i] != '\0'; i++)
    {
        c1 = s1[i];
        if (c1 >= 'A' && c1 <= 'Z')
            c1 = c1 + ('a' - 'A'); // 大写转小写
        c2 = s2[i];
        if (c2 >= 'A' && c2 <= 'Z')
            c2 = c2 + ('a' - 'A'); // 大写转小写
        if (c1 != c2)
        {
            return c1 - c2;
        }
    }
    // c1 和 c2 再次计算，处理因遇到 '\0' 结束时的差异
    c1 = s1[i];
    if (c1 >= 'A' && c1 <= 'Z')
        c1 = c1 + ('a' - 'A');

    c2 = s2[i];
    if (c2 >= 'A' && c2 <= 'Z')
        c2 = c2 + ('a' - 'A');

    return c1 - c2;
}

/***************************************************************************
  函数名称：
  功    能：比较字符串 s1 和 s2 的前 len 个字符的 大小，英文字母要区分大小写
若 len 大于 s1/s2 中长度短的串，则比较到短串的\0即结束
  输入参数：
  返 回 值：相等为0，不等则为第1个不相等字符的ASCII差值
  说    明：
***************************************************************************/
int tj_strncmp(const char s1[], const char s2[], const int len)
{
    /* 注意：函数内不允许定义任何形式的数组（包括静态数组） */
    int i = 0;
    for (i = 0; i < len; i++)
    {
        if (s1[i] == '\0' || s2[i] == '\0')
            break;
        if (s1[i] != s2[i])
            return s1[i] - s2[i];
    }
    if (i == len) 
    {
        // 情况 1: 达到 len 限制，且 len 个字符都相等
        return 0;
    }
    // 情况 2: 遇到短串的 '\0' 结束，返回 '\0' 和另一个字符的差值
    return s1[i] - s2[i];
}

/***************************************************************************
  函数名称：
  功    能：比较字符串 s1和 s2 的前 len 个字符的 大小，英文字母不分大小写
    长度要求同 tj_strncmp 
    大小写要求同 tj_strcasecmp 
  输入参数：
  返 回 值：相等为0，不等则为第1个不 相等字符的ASCII差值
  说    明：
***************************************************************************/
int tj_strcasencmp(const char s1[], const char s2[], const int len)
{
    /* 注意：函数内不允许定义任何形式的数组（包括静态数组） */
    int i = 0;
    int c1, c2;
    for (i = 0; i < len; i++)
    {
        // 如果遇到任一串结束，则跳出
        if (s1[i] == '\0' || s2[i] == '\0')
            break;
        c1 = s1[i];
        if (c1 >= 'A' && c1 <= 'Z')
            c1 = c1 + ('a' - 'A');
        c2 = s2[i];
        if (c2 >= 'A' && c2 <= 'Z')
            c2 = c2 + ('a' - 'A');
        if (c1 != c2)
        {
            return c1 - c2;
        }
    }
    // 如果循环是因为 i == len 结束，则前 len 个字符相等，返回 0
    if (i == len)
        return 0;
    // 如果循环是因为 '\0' 结束，返回转换为小写后的差值
    c1 = s1[i];
    if (c1 >= 'A' && c1 <= 'Z')
        c1 = c1 + ('a' - 'A');
    c2 = s2[i];
    if (c2 >= 'A' && c2 <= 'Z')
        c2 = c2 + ('a' - 'A');
    return c1 - c2;
}


