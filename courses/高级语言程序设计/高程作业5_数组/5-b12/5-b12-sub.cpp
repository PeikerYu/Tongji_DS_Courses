    int len = tj_strlen(str);
    int left = 0;
    int right = len - 1;
    char temp; 
    while (left < right)
    {
        temp = str[left];
        str[left] = str[right];
        str[right] = temp;

        left++;
        right--;
    }
    return 0; //return值可根据需要修改
