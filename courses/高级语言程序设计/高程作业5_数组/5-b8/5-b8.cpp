/***************************************************************************
 * 函数名称：input_pure_decimal
 * 功 能：输入一个二进制纯小数，并记录实际输入长度
 * 输入参数：
 * 返 回 值：
 * 说 明：
 ***************************************************************************/
void input_pure_decimal(char pure_decimal[])
{
    char s[300];
    cout << "请输入一个二进制纯小数，小数点开头，小数点后不超过112位(例：.101101)\n";
    while (1)
    {
        cin >> s;
        if (!cin.good())
        {
            cin.clear();
            cin.ignore(65536, '\n');
            continue;
        }
        if (s[0] != '.')
        {
            cout << "不是以.开头，请重输\n";
            cin.ignore(65536, '\n');
            continue;
        }
        bool tag = 1;
        for (int i = 1; s[i] != '\0'; i++)
        {
            if (s[i] != '0' && s[i] != '1')
            {
                tag = 0;
                break;
            }
        }
        if (tag == 0)
        {
            cout << "输入的不是0/1，请重输\n";
            cin.ignore(65536, '\n');
            continue;
        }
        bool all_zero = 1;
        for (int i = 1; s[i] != '\0'; i++)
        {
            if (s[i] != '0')
            {
                all_zero = 0;
                break;
            }
        }
        if (all_zero)
        {
            if (s[1] == '\0')
                cout << "输入数据为空，请重输\n";
            else
                cout << "输入为全0，请重输\n";
            cin.ignore(65536, '\n');
            continue;
        }
        
        //去除尾随零
        int last_one_index = 0; // 记录最后一个 '1' 的下标 (从 s[1] 开始)
        int max_index = 0;      // 记录实际输入的字符串的最大下标

        for (int i = 1; s[i] != '\0' && i <= N_POW; i++)   // 遍历字符串找到最后一个 '1' 的位置
        {
            pure_decimal[i] = s[i] - '0'; // 字符转数字 0 或 1
            if (pure_decimal[i] == 1) 
            {
                last_one_index = i;
            }
            max_index = i; // 记录字符串的实际长度
        }

        int effective_length = last_one_index; //有效输出长度

        pure_decimal[0] = effective_length;
        break;
    }
}
