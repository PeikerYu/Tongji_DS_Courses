/***************************************************************************
 * 函数名称：output_decimal_value (原 output)
 * 功 能：输出十进制值（2^-i 和 计算值，带 0.，并去除末尾非有效零）
 * 输入参数：
 * 返 回 值：
 * 说 明：
 ***************************************************************************/
void output_decimal_value(const char prompt[], const char d[])
{
    if (prompt[0] != '\0')
    {
        cout << prompt;
    }
    else
    {
        cout << "2^" << setw(4) << int(d[0]) << " : ";
    }
    cout << "0."; // 十进制输出固定有 "0."

    int last = N_NUM; // 找到最后一个非零数字
    while (last > 1 && d[last] == 0)
        last--;

    for (int i = 1; i <= last; i++)
    {
        cout << int(d[i]);
    }
    cout << endl;
}
/***************************************************************************
 * 函数名称：output_binary_input
 * 功 能：输出二进制纯小数输入 (格式：1011，无 0.，不输出后面的0填充)
 * 输入参数：prompt：输出提示串；d：二进制数字数组
 * 返 回 值：
 * 说 明：
 ***************************************************************************/
void output_binary_input(const char prompt[], const char d[])
{
    cout << prompt;
    // 从 d[0] 中取出在 input_pure_decimal 中记录的输入长度
    int length = int(d[0]);

    for (int i = 1; i <= length; i++)
    {
        // d[i] 存储的是数字 0 或 1
        cout << int(d[i]);
    }
    cout << endl;
}
/***************************************************************************
  函数名称：
  功 能：用二维数组第i行的值，计算第i+1行
  输入参数：
  返 回 值：
  说 明：
***************************************************************************/
void calc_next(char d_cur[], char d_next[])
{
    int carry = 0; //记录上一位除以2的余数，0或者1
    for (int i = 1; i<=N_NUM; i++)
    {
        int val = carry * 10 + int(d_cur[i]);
        d_next[i] = val / 2;
        carry = val % 2;
    }
}
/***************************************************************************
  函数名称：
  功 能：根据幂次表，计算某个二进制小数的十进制值
  输入参数：char pure_decimal[] : 存放二进制小数的数组
            char out[] ：存放计算得到的十进制小数
   char power_table[][N_NUM + 1]：幂次表
  返 回 值：
  说 明：
 ***************************************************************************/
void calc_num(char pure_decimal[], char out[], char power_table[][N_NUM + 1])
{
    for (int bi = 1; bi <= N_POW; bi++)
    {
        if (pure_decimal[bi] == 1)
        {
            int carry = 0;
            for (int j = N_NUM; j >= 1; j--) //从右往左实现加法
            {
                int sum = out[j] + carry + power_table[bi][j];
                out[j] = sum % 10;
                carry = sum / 10;
            }
        }
    }
}
